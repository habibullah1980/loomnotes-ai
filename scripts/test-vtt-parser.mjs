/**
 * WebVTT Cleaner utility for Loom Captions
 */
export function parseWebVTTToCleanText(vttContent) {
  if (!vttContent || typeof vttContent !== "string") return "";

  // Split into lines
  const lines = vttContent.replace(/\r\n/g, "\n").split("\n");
  const textLines = [];
  let lastLine = "";

  for (let line of lines) {
    line = line.trim();

    // Skip empty lines, WEBVTT header, NOTE blocks, and timestamp arrow lines
    if (!line) continue;
    if (line.startsWith("WEBVTT") || line.startsWith("NOTE") || line.startsWith("STYLE")) continue;
    if (/^\d+$/.test(line)) continue; // Cue number
    if (/-->/.test(line)) continue; // Timestamp range (00:00.000 --> 00:04.000)

    // Remove any inline WebVTT tags like <v Speaker>, <c.color>, etc.
    const cleanLine = line.replace(/<[^>]+>/g, "").trim();
    if (!cleanLine) continue;

    // Deduplicate consecutive identical lines often generated by rolling caption streams
    if (cleanLine !== lastLine) {
      textLines.push(cleanLine);
      lastLine = cleanLine;
    }
  }

  // Join lines into readable paragraphs
  return textLines.join(" ");
}

/**
 * Loom JSON Transcript Cleaner
 */
export function parseLoomJsonToCleanText(jsonData) {
  if (!jsonData) return "";

  if (typeof jsonData === "string") {
    try {
      jsonData = JSON.parse(jsonData);
    } catch {
      return jsonData;
    }
  }

  // Handle array of segments: [{ text: "..." }, ...]
  if (Array.isArray(jsonData)) {
    return jsonData
      .map((item) => (typeof item === "string" ? item : item?.text || item?.content || item?.phrase || ""))
      .filter(Boolean)
      .join(" ");
  }

  // Handle object with phrases / segments / transcript
  if (typeof jsonData === "object") {
    const obj = jsonData;
    if (Array.isArray(obj.phrases)) {
      return obj.phrases.map((p) => p?.text || p?.phrase || "").filter(Boolean).join(" ");
    }
    if (Array.isArray(obj.segments)) {
      return obj.segments.map((s) => s?.text || s?.content || "").filter(Boolean).join(" ");
    }
    if (Array.isArray(obj.words)) {
      return obj.words.map((w) => w?.text || w?.word || "").filter(Boolean).join(" ");
    }
    if (typeof obj.transcript === "string") {
      return obj.transcript;
    }
  }

  return "";
}

